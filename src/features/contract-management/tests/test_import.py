def test_imported_contracts_work_through_the_api(
    make_owner: Callable[..., Owner], make_client: Callable[..., TestClient], source: str
) -> None:
    owner = make_owner()
    _entry(source, owner, "移行したアカウント", user="taro", pw="migrated-pw", site="https://m.example")
    _run(source)
    c = make_client(owner)
    [item] = c.get("/accounts").json()["items"]
    assert item["name"] == "移行したアカウント" and item["username"] == "taro" and item["has_password"] is True
    assert c.get(f"/contracts/{item['id']}/password").json() == {"password": "migrated-pw"}
    detail = c.get(f"/contracts/{item['id']}").json()
    assert detail["has_contract"] is False and detail["category"]["name"] == "その他" and detail["login_methods"] == ["password"]
    # 画面から、通常の契約と同じように編集できる（取り込み元の ID は変わらない）
    res = c.patch(f"/contracts/{item['id']}", json={"name": "改名", "has_contract": False, "login_methods": ["password"], "username": "taro"})
    assert res.status_code == 200 and c.get(f"/contracts/{item['id']}/password").json() == {"password": "migrated-pw"}
