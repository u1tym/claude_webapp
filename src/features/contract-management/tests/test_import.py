def test_failures_do_not_stop_the_others(make_owner: Callable[..., Owner], source: str) -> None:
    owner = make_owner()
    ok1 = _entry(source, owner, "正常1")
    long_title = _entry(source, owner, "あ" * 201)
    blank_title = _entry(source, owner, "   ")
    ok2 = _entry(source, owner, "正常2")
    result = _run(source)
    assert result.imported == 2 and result.target == 4
    assert {entry_id for entry_id, _ in result.failures} == {long_title, blank_title}
    assert all(reason for _, reason in result.failures)
    assert [r["imported_from_entry_id"] for r in _contracts(owner)] == [ok1, ok2]


def test_main_output_and_log_have_no_secrets(
    make_owner: Callable[..., Owner], source: str, capsys: pytest.CaptureFixture[str], log_dir: Path
) -> None:
    owner = make_owner()
    _entry(source, owner, "秘密のタイトル", user="secret-user-name", pw="S3cret-Pass", memo="秘密のメモ")
    _entry(source, owner, "い" * 201, user="secret-user-2", pw="S3cret-Pass-2")  # 失敗する行
    code = imp.main(["--source-schema", source])
    out = capsys.readouterr()
    text = out.out + out.err + (log_dir / LOG_FILE).read_text(encoding="utf-8")
    assert code == 1  # 取り込めなかった行がある
    assert "取り込み完了" in out.out and "対象のエントリ: 2 件" in out.out and "取り込み: 1 件" in out.out
    assert "取り込めなかった: 1 件" in out.out and "エントリ ID" in out.out
    for secret in ("秘密のタイトル", "secret-user-name", "S3cret-Pass", "secret-user-2", "秘密のメモ", "い" * 50):
        assert secret not in text, secret
    assert len(_contracts(owner)) == 1


